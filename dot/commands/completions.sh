# dot completions: write home/.config/fish/completions/dot.fish from the
# command list (DOT_COMMAND_SUMMARIES); component names complete at runtime
# through `dot components --names`.

cmd_completions_usage() {
    cat << EOF
USAGE:
    ${SCRIPT_NAME} completions

Regenerate home/.config/fish/completions/dot.fish (stowed to ~/.config/fish).
EOF
}

cmd_completions() {
    __require_no_args completions "$@" || return 1
    local completions_file="${HOME_DIR}/.config/fish/completions/dot.fish"
    mkdir -p "$(dirname "$completions_file")"

    __write_fish_completions > "$completions_file"
    __print_success "Fish completions written to ${completions_file}"
}

__write_fish_completions() {
    local summary command_names=""
    for summary in "${DOT_COMMAND_SUMMARIES[@]}"; do
        command_names+="${summary%%|*} "
    done
    command_names="${command_names% }"

    cat << 'EOF'
# Fish completions for dot. Generated by `dot completions` (dot/commands/completions.sh); do not edit.

complete -c dot -f
complete -c dot -n "__fish_use_subcommand" -l version -d "Show version information"
complete -c dot -n "__fish_use_subcommand" -s h -l help -d "Show help"

EOF
    echo "# Commands"
    for summary in "${DOT_COMMAND_SUMMARIES[@]}"; do
        printf 'complete -c dot -n "__fish_use_subcommand" -a "%s" -d "%s"\n' "${summary%%|*}" "${summary#*|}"
    done
    echo "complete -c dot -n \"__fish_seen_subcommand_from help\" -a \"${command_names}\""

    cat << 'EOF'

# init, update, doctor: component selection
complete -c dot -n "__fish_seen_subcommand_from init update doctor" -l only -x -a "(dot components --names 2>/dev/null)" -d "Only these components (comma-separated)"
complete -c dot -n "__fish_seen_subcommand_from init update doctor" -l skip -x -a "(dot components --names 2>/dev/null)" -d "Skip these components (comma-separated)"
complete -c dot -n "__fish_seen_subcommand_from init update" -l dry-run -d "Print the plan and change nothing"
complete -c dot -n "__fish_seen_subcommand_from init" -l headless -d "No prompts or font (remote VMs)"
complete -c dot -n "__fish_seen_subcommand_from init" -l skip-ssh -d "Same as --skip ssh_key"
complete -c dot -n "__fish_seen_subcommand_from init" -l skip-font -d "Same as --skip font"
complete -c dot -n "__fish_seen_subcommand_from update" -l no-pull -d "Skip the git pull"
complete -c dot -n "__fish_seen_subcommand_from components" -l names -d "Print only component names"

# package
set -l __dot_package_subcommands list add remove update help
complete -c dot -n "__fish_seen_subcommand_from package; and not __fish_seen_subcommand_from $__dot_package_subcommands" -a list -d "List packages (default)"
complete -c dot -n "__fish_seen_subcommand_from package; and not __fish_seen_subcommand_from $__dot_package_subcommands" -a add -d "Install a package and add it to a list"
complete -c dot -n "__fish_seen_subcommand_from package; and not __fish_seen_subcommand_from $__dot_package_subcommands" -a remove -d "Remove a package from lists"
complete -c dot -n "__fish_seen_subcommand_from package; and not __fish_seen_subcommand_from $__dot_package_subcommands" -a update -d "Upgrade packages"
complete -c dot -n "__fish_seen_subcommand_from package; and not __fish_seen_subcommand_from $__dot_package_subcommands" -a help -d "Show package help"
complete -c dot -n "__fish_seen_subcommand_from package; and __fish_seen_subcommand_from add" -a "brew cask apt pacman" -d "Package type"
complete -c dot -n "__fish_seen_subcommand_from package; and __fish_seen_subcommand_from add remove update list" -a "base work" -d "Package list"
complete -c dot -n "__fish_seen_subcommand_from package; and __fish_seen_subcommand_from update list" -a all -d "Every package"

# benchmark-shell
complete -c dot -n "__fish_seen_subcommand_from benchmark-shell" -s r -l runs -x -a "5 10 20 50" -d "Number of runs"
complete -c dot -n "__fish_seen_subcommand_from benchmark-shell" -s v -l verbose -d "Show each timing"
EOF
}
